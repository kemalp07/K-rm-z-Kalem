// Scans assets/art and assets/sfx and writes static require() manifests.
// Metro cannot require dynamic paths, so drop a file in, then run `npm run assets`.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');

function build(dir, exts, exportName, typeImport) {
  const abs = path.join(root, dir);
  const files = fs
    .readdirSync(abs)
    .filter((f) => exts.includes(path.extname(f).toLowerCase()))
    .sort();
  const lines = files.map((f) => `  ${JSON.stringify(path.basename(f, path.extname(f)))}: require('./${f}'),`);
  const body = [
    '// GENERATED by scripts/gen-asset-manifests.js — do not edit by hand.',
    typeImport,
    '',
    `export const ${exportName}: Partial<Record<string, number>> = {`,
    ...lines,
    '};',
    '',
  ]
    .filter((l) => l !== null)
    .join('\n');
  fs.writeFileSync(path.join(abs, 'manifest.ts'), body);
  console.log(`${dir}: ${files.length ? files.join(', ') : '(empty — placeholders/silence)'}`);
}

build('assets/art', ['.png', '.jpg', '.jpeg', '.webp'], 'artFiles', '/* eslint-disable */');
build('assets/sfx', ['.mp3', '.m4a', '.wav', '.ogg'], 'sfxFiles', '/* eslint-disable */');
